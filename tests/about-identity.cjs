const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const business=require('../business.json');
const render=require('../content/about-identity.cjs').section;
const html=fs.readFileSync(path.join(__dirname,'../about/index.html'),'utf8');
const moduleHTML=render(business);
assert(!/<details\b|<summary\b|\shidden(?:\s|=|>)|aria-expanded|data-toggle/.test(moduleHTML),'All identity data is available without disclosure state');
assert.equal((moduleHTML.match(/<dd\b/g)||[]).length,8,'Two identifiers and six public registration fields');
assert(moduleHTML.includes('ABN 登记日期')&&moduleHTML.includes('ABN registered from'),'ABN date is labelled as a registration start, not an expiry');
assert(!moduleHTML.includes('ABN 有效日期'),'No ambiguous expiry-style label');
const nameText=moduleHTML.match(/<h2[^>]*id="identity-title"[^>]*>([\s\S]*?)<\/h2>/)[1].replace(/<[^>]+>/g,'').replace(/\s+/g,' ').trim();
assert.equal(nameText,business.legalName,'The complete legal name remains real text');
for(const field of ['abn','acn','abnStatus','entityType','registeredRegion','registerUrl'])assert(moduleHTML.includes(business[field]),'Confirmed field: '+field);
assert(moduleHTML.includes('11 November 2020'),'Confirmed full dates remain readable');
assert(moduleHTML.includes('13 November 2026'),'Original verification date retained');
assert(moduleHTML.includes('Registered'),'GST registration remains visible');
assert(moduleHTML.includes('href="/areas/melbourne/" data-local-page'),'Existing regional route uses the shared locale mechanism');
assert.equal(new URL(business.registerUrl).searchParams.get('id'),business.abn.replace(/\s/g,''),'Official lookup uses the confirmed ABN');
for(const file of ['assets/about-identity/registration-badge.png','areas/melbourne/index.html','contact/index.html'])assert(fs.existsSync(path.join(__dirname,'..',file)),file+' exists');
assert(html.includes(moduleHTML),'Built About contains the open identity module');
assert(!html.includes('ap-registration-details'),'Retired disclosure removed from generated About');
assert(html.includes('$20M')&&html.includes('Public Liability Insurance')&&html.includes('2000万澳币公众责任险'),'Insurance retained');
assert(html.includes('href="/contact/" data-local-page'),'Existing contact entry retained');
// A changed business source must flow through, rather than retaining values read from the mockup.
const changed=render({...business,abn:'11 222 333 444',acn:'222 333 444',registeredRegion:'VIC 3999, Australia',activeFrom:'2021-02-03',gstFrom:'2021-02-04',verifiedOn:'2026-11-14'});
assert(changed.includes('11 222 333 444')&&changed.includes('222 333 444')&&changed.includes('VIC 3999, Australia'));
assert(changed.includes('3 February 2021')&&changed.includes('4 February 2021')&&changed.includes('14 November 2026'));
console.log('About identity checks passed: 8 open data fields, confirmed source values, original insurance and routes, dynamic source propagation.');
